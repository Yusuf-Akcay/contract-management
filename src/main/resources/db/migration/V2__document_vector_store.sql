CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE uploaded_document (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    filename     VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes   BIGINT       NOT NULL,
    chunk_count  INTEGER      NOT NULL,
    version      BIGINT       NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by   VARCHAR(255),
    updated_by   VARCHAR(255)
);

-- Layout expected by Spring AI's PgVectorStore; dimensions must match the embedding model
CREATE TABLE vector_store (
    id        UUID PRIMARY KEY,
    content   TEXT,
    metadata  JSON,
    embedding VECTOR(${embedding_dimensions})
);

CREATE INDEX idx_vector_store_embedding ON vector_store USING hnsw (embedding vector_cosine_ops);
