CREATE TABLE customer (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_number VARCHAR(20)  NOT NULL,
    first_name      VARCHAR(100) NOT NULL,
    last_name       VARCHAR(100) NOT NULL,
    date_of_birth   DATE         NOT NULL,
    email           VARCHAR(255),
    version         BIGINT       NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by      VARCHAR(255),
    updated_by      VARCHAR(255),
    CONSTRAINT uk_customer_customer_number UNIQUE (customer_number)
);

CREATE TABLE contract (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_number  VARCHAR(20)    NOT NULL,
    customer_id      BIGINT         NOT NULL,
    line_of_business VARCHAR(20)    NOT NULL,
    premium          NUMERIC(12, 2) NOT NULL,
    start_date       DATE           NOT NULL,
    end_date         DATE,
    status           VARCHAR(20)    NOT NULL,
    version          BIGINT         NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_by       VARCHAR(255),
    updated_by       VARCHAR(255),
    CONSTRAINT uk_contract_contract_number UNIQUE (contract_number),
    CONSTRAINT fk_contract_customer FOREIGN KEY (customer_id) REFERENCES customer (id),
    CONSTRAINT ck_contract_premium CHECK (premium > 0),
    CONSTRAINT ck_contract_date_range CHECK (end_date IS NULL OR end_date > start_date)
);

CREATE INDEX idx_contract_customer ON contract (customer_id);
